'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('netlify/functions/_sanctum-lineup-eligibility.js','utf8');
assert(source.includes("readCachedWeeklySchedule"));
assert(source.includes("schedule.activeTeams.length + schedule.byeTeams.length === 32"));
assert(source.includes("injuryFresh"));
assert(source.includes("blockedInjury"));
assert(source.includes("blockedNames"));
const chat = fs.readFileSync('netlify/functions/chat.js','utf8');
assert(chat.includes("buildLineupEligibility(messages)"));
assert(chat.includes("unsafeRecommendation(fullText, lineupEligibility.blockedNames)"));
assert(chat.includes("Blocked unverified or ineligible lineup substitution"));
const prompt = 'It is NFL Week 7. Here is my current lineup:\n\nSTARTERS:\nWide Receiver: DeVonta Smith\n\nBENCH:\nJakobi Meyers, Blake Corum\n\nPlease analyze my lineup';
const start = source.indexOf('function lineupRequest(messages) {');
const end = source.indexOf('\nconst normalize',start);
const context = {};
vm.createContext(context);
vm.runInContext(source.slice(start,end)+'\nthis.parse = lineupRequest;',context);
const parsed = context.parse([{role:'user',content:prompt}]);
assert.equal(parsed.week,7);
assert.equal(parsed.names.join(','),'DeVonta Smith,Jakobi Meyers,Blake Corum');
console.log('PASS: week-specific lineup extraction, schedule/injury gates, response safety hook');
