'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('netlify/functions/_sanctum-lineup-eligibility.js','utf8');
const begin = source.indexOf('function lineupRequest(messages) {');
const end = source.indexOf('\nconst normalize',begin);
assert(begin >= 0 && end > begin);
const context = {};
vm.createContext(context);
vm.runInContext(source.slice(begin,end)+'\nthis.parse=lineupRequest;',context);
const freeform = context.parse([{role:'user',content:"It's Week 7. Jakobi Meyers is on my bench. Should I move him into my starting lineup? Please check his team's bye week and injury status."}]);
assert.equal(freeform.week,7);
assert.equal(freeform.names.length,0);
assert.match(freeform.freeform,/Jakobi Meyers/);
assert.equal(context.parse([{role:'user',content:'What about Week 7 waiver values?'}]),null);
const chat = fs.readFileSync('netlify/functions/chat.js','utf8');
assert(chat.includes('lineupEligibility?.freeform'));
assert(chat.includes('row.status === "BYE"'));
assert(chat.includes('row.status === "UNVERIFIED"'));
assert(chat.includes('Do not start him this week.'));
const byeQuestion = "what NFL teams are on BYE for week 7";
const questionPattern = /\\b(?:which|what|list|name|who)\\b[\\s\\S]{0,90}\\b(?:teams?|nfl teams?)\\b[\\s\\S]{0,90}\\bbye\\b|\\b(?:teams?|nfl teams?)\\b[\\s\\S]{0,90}\\b(?:on|have|with)\\s+(?:a\\s+)?byes?\\b/i;
assert.ok(questionPattern.test(byeQuestion), 'exact customer team-bye question must match');
assert.equal(context.parse([{role:'user',content:byeQuestion}]).week,7);
assert.match(chat, /teamByeQuestion && lineupEligibility\\?\\.freeform/);
assert.match(chat, /lineupEligibility\\.byeTeams/);
assert.match(chat, /bye-week schedule is not verified/);
const eligibilitySource = fs.readFileSync('netlify/functions/_sanctum-lineup-eligibility.js','utf8');
assert.match(eligibilitySource, /byeTeams: scheduleValid \\? \\[\\.\\.\\.schedule\\.byeTeams\\] : null/);
console.log('PASS: freeform Week 7 lineup eligibility and direct team bye question');
